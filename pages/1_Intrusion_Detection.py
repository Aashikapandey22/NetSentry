def format_pct(value: float) -> str:
    """
    Formats a percentage value with dynamic precision.
    Ensures tiny values (e.g., 0.0045%) are never rounded down to 0.0%.
    """
    if value == 0.0:
        return "0.00%"
    elif value < 0.01:
        # Show at least 4 decimal places for very small percentages
        return f"{value:.4f}%"
    elif value < 0.1:
        return f"{value:.3f}%"
    else:
        return f"{value:.2f}%"


